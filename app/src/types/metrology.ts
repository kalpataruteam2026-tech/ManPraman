export type AccuracyClass = 'I' | 'II' | 'III' | 'IV';
export type TestMode = 'ModelApproval' | 'InitialVerification' | 'InServiceVerification';

// ==========================================
// TIER 1: ADMINISTRATIVE & ENVIRONMENTAL
// ==========================================
export interface AdministrativeInfo {
  // Test Context
  testMode: TestMode;
  testingAuthority: string;
  inspectorName: string;
  
  // Applicant Info
  applicantName: string;
  applicantAddress: string;
  licenseNumber: string;
  
  // Environmental Conditions
  ambientTemperature: number; // °C
  relativeHumidity: number;   // %
  atmosphericPressure?: number; // kPa (optional for some tests)
  
  // Reference Standards Used
  standardWeightsId: string;
  standardWeightsClass: 'E1' | 'E2' | 'F1' | 'F2' | 'M1' | 'M2';
  calibrationExpiryDate: string;
}

// ==========================================
// TIER 2: INSTRUMENT SPECIFICATIONS
// ==========================================
export interface InstrumentSpecs {
  serialNumber: string;
  manufacturer: string;
  model: string;
  accuracyClass: AccuracyClass;
  
  // Capacities
  maxCapacity: number; // Max
  minCapacity: number; // Min
  verificationScaleInterval: number; // e
  actualScaleInterval: number; // d
  
  // Hardware/Software Info
  softwareVersion: string;
  softwareHash?: string; // SHA-256
  isMultiInterval: boolean;
}

// ==========================================
// TIER 3: EMPIRICAL TEST OBSERVATIONS
// ==========================================
// A single reading during a test
export interface TestReading {
  stepIndex: number;
  loadApplied: number; // L
  indicatedValue: number; // I
  deltaLoad: number; // ΔL (fractional weights added)
}

// Eccentricity Test (Corner Load)
export interface EccentricityTest {
  testLoad: number;
  positions: {
    center: TestReading;
    position1: TestReading;
    position2: TestReading;
    position3: TestReading;
    position4: TestReading;
  };
}

// Weighing Performance Test
export interface WeighingPerformanceTest {
  zeroSetting: TestReading;
  increasingLoads: TestReading[]; // Array of readings going up to Max
  decreasingLoads: TestReading[]; // Array of readings coming down to Zero
}

// Repeatability Test
export interface RepeatabilityTest {
  testLoad: number;
  runs: TestReading[]; // Array of 3 to 10 runs depending on test mode
}

// Complete Input Payload from User/UI
export interface OIMLTestSessionInput {
  administrativeInfo: AdministrativeInfo;
  instrumentSpecs: InstrumentSpecs;
  eccentricityTest: EccentricityTest;
  weighingPerformanceTest: WeighingPerformanceTest;
  repeatabilityTest: RepeatabilityTest;
}

// ==========================================
// OUTPUT STRUCTURES
// ==========================================

// Calculated Result for a Single Point
export interface PointResult {
  reading: TestReading;
  calculatedP: number; // P = I + 0.5d - ΔL
  errorE: number; // E = P - L
  correctedErrorEc: number; // Ec = E - E0
  allowedMPE: number; // ± MPE limit
  isPass: boolean;
}

// 2026 Substitution Rule Output
export interface SubstitutionRuleOutput {
  repeatabilityError: number;
  tierApplied: '20%' | '33.3%' | '50%';
  requiredStandardWeightTonnage: number;
}

// The Final Structured Output generated by the engine
export interface OIMLTestReportOutput {
  sessionId: string;
  timestamp: string;
  
  // Reflected Inputs
  administrativeInfo: AdministrativeInfo;
  instrumentSpecs: InstrumentSpecs;
  
  // Calculated Results
  zeroErrorE0: number;
  weighingResults: PointResult[];
  eccentricityResults: PointResult[];
  substitutionAdvisory: SubstitutionRuleOutput;
  
  overallVerdict: 'PASS' | 'FAIL';
  
  // Security
  digitalSignatureHash: string;
}
